#!/usr/bin/env python3
"""
creature_protos.py - make FOC's own creature (animal) critter protos from a table.

    python tools/creature_protos.py --dry-run
    python tools/creature_protos.py            # write protos + names; then gen_ids/build/deploy

Each row is one creature: a fixed proto index, a display name, a look
(critters.lst art name), a vanilla template proto (body type, AI packet, team,
kill type, damage type, flags), SPECIAL, and the totals the player meets.

Stats go through foclib.critter_stats: base = derived from SPECIAL, bonus =
total - base, because the engine recomputes the base whenever one is spawned.

What is written:
  mod/data/proto/critters/<index>.pro   template bytes, then:
      pid @0, message_id @4, fid @8, script @28 = -1
      SPECIAL         baseStats[0..6] @48
      derived stats   base = engine formula, bonus @188 = total - base
      DT / DR         baseStats[17..30] (not derived)
      unarmed skill   skills[3] @328
      experience      @404
  mod/ids/proto_critters.txt, msg_critters.txt, msg_critters_desc.txt
  mod/data/text/english/game/pro_crit.msg (regenerated by port.write_merged_msg)
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import port  # noqa: E402
from npc_protos import CRIT_DIR, DESCS, NAMES, REG, START, art_index, registry  # noqa: E402
from foclib import GameIndex  # noqa: E402
from foclib.critter_stats import (AC, AG, AP, CH, CRIT, EN, HP, IN, LK, MELEE,  # noqa: E402
                                  PE, SEQ, ST, set_total)

STATS_OFF, BONUS_OFF, SKILLS_OFF, XP_OFF = 48, 188, 328, 404
DT_NORMAL, DR_NORMAL = 17, 24
SKILL_UNARMED = 3

TOUGH_PIG_RAT = 0x1000071   # vanilla 113: pig rat AI packet, kill type and body
MOLE_RAT = 0x100006E        # vanilla 110: the mole rat's AI packet, kill type, body and animations


# index: dict of name, art, template, SPECIAL, totals, DT/DR, unarmed, xp, description
CREATURES = {
    # Clairemont courthouse (CLCOURT.MAP). Early game: the player comes here
    # straight from Kilgore's gecko hunt (five Little Geckos, 25 HP / 55 XP),
    # and Clairemont's own fighters are Thorne's riders (45 HP). A hograt is a
    # step up from a Little Gecko: about as tough, hits harder, easier to hit.
    # The look is the mole rat shrunk to a pig rat's size (tools/scale_critter.py
    # MAMRAT MAHOGX --like MAMURT, owner 2026-10-20), so it is on the mole rat.
    852: dict(
        name="Hograt", art="mahogx", template=MOLE_RAT,
        special={ST: 5, PE: 4, EN: 4, CH: 1, IN: 1, AG: 5, LK: 2},
        totals={HP: 30, AP: 7, AC: 8, MELEE: 6, SEQ: 8, CRIT: 3},
        dt=1, dr=10, unarmed=45, xp=70,
        desc="A mole rat no bigger than a pig rat, bristly and quick, with long yellow teeth."),
    # A raccoon grown to the size of a man, from the Fallout 1 raccoon art pack
    # (tools/import_critter_frms.py). Same tier as the hograt: quicker and
    # harder to hit, a little less tough.
    882: dict(
        name="Raccoon", art="racoon", template=TOUGH_PIG_RAT,
        special={ST: 5, PE: 5, EN: 4, CH: 1, IN: 2, AG: 6, LK: 3},
        totals={HP: 28, AP: 8, AC: 10, MELEE: 6, SEQ: 9, CRIT: 4},
        dt=0, dr=10, unarmed=45, xp=65,
        desc="A raccoon that has grown to the size of a man. It stands hunched, with coarse dark fur and long claws."),
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gi = GameIndex(pristine=False)
    reg = registry(REG)
    entries = [l for l in reg if l.strip() and not l.startswith("#")]
    header = len(reg) - len(entries)
    names = port.registry_entries(NAMES)
    descs = {k: v for k, v in (l.split("\t", 1) for l in registry(DESCS) if "\t" in l)}

    for idx, c in sorted(CREATURES.items()):
        fn = f"{idx:08d}.pro"
        pos = idx - START
        if pos < len(entries):
            if entries[pos] != fn:
                sys.exit(f"proto_critters line for index {idx} is {entries[pos]!r}, not {fn}")
        elif pos == len(entries):
            entries.append(fn)
        else:
            sys.exit(f"index {idx} would leave a gap after {START + len(entries) - 1}")

        if c["name"] not in names:
            names.append(c["name"])
        msg_id = port.msg_id_for_index(names.index(c["name"]))
        descs[c["name"]] = c["desc"]

        buf = bytearray(gi.vfs.read(gi.proto_path(c["template"])))
        struct.pack_into(">i", buf, 0, (1 << 24) | idx)
        struct.pack_into(">i", buf, 4, msg_id)
        struct.pack_into(">i", buf, 8, 0x01000000 | art_index(c["art"]))
        struct.pack_into(">i", buf, 28, -1)
        for stat, v in c["special"].items():
            struct.pack_into(">i", buf, STATS_OFF + 4 * stat, v)
            struct.pack_into(">i", buf, BONUS_OFF + 4 * stat, 0)
        for stat, value in c["totals"].items():
            set_total(buf, stat, value)
        struct.pack_into(">i", buf, STATS_OFF + 4 * DT_NORMAL, c["dt"])
        struct.pack_into(">i", buf, STATS_OFF + 4 * DR_NORMAL, c["dr"])
        struct.pack_into(">i", buf, SKILLS_OFF + 4 * SKILL_UNARMED, c["unarmed"])
        struct.pack_into(">i", buf, XP_OFF, c["xp"])

        t = c["totals"]
        print(f"  {fn}  {c['name']:14} art {c['art']}  HP {t[HP]} AP {t[AP]} AC {t[AC]} "
              f"melee {t[MELEE]}  unarmed {c['unarmed']}  XP {c['xp']}  msg {msg_id}")
        if not args.dry_run:
            (CRIT_DIR / fn).write_bytes(bytes(buf))

    if args.dry_run:
        return 0
    REG.write_text("\n".join(reg[:header] + entries) + "\n", encoding="utf-8")
    NAMES.write_text("\n".join(names) + "\n", encoding="utf-8")
    DESCS.write_text("".join(f"{k}\t{v}\n" for k, v in descs.items()), encoding="utf-8")
    port.write_merged_msg("critters")
    print("names and descriptions written; now run gen_ids.py, build.py, deploy.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
