# NPCs who trade: the critter "barter" flag (critter flags @44, bit 0x2)
BARTER = {849, 864, 865}
CRITTER_FLAGS_OFF, CRITTER_BARTER = 44, 0x2


def art_index(name: str) -> int:
    lst = parse_lst((ROOT / "base" / "mods" / "foc" / "art" / "critters" / "critters.lst").read_bytes())
    for i, n in enumerate(lst):
        if n.split(",")[0].strip().lower() == name.lower():
            return i
    sys.exit(f"art {name!r} is not in critters.lst")


def registry(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines() if path.exists() else []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    gi = GameIndex(pristine=False)
    reg = registry(REG)
    entries = [l for l in reg if l.strip() and not l.startswith("#")]
    header = len(reg) - len(entries)
    names = port.registry_entries(NAMES)
    descs = {k: v for k, v in (l.split("\t", 1) for l in registry(DESCS) if "\t" in l)}

    for idx, (name, art, tmpl, hp, gender, gun, desc) in sorted(NPCS.items()):
        fn = f"{idx:08d}.pro"
        pos = idx - START
        if pos < len(entries):
            if entries[pos] != fn:
                sys.exit(f"proto_critters line for index {idx} is {entries[pos]!r}, not {fn}")
        elif pos == len(entries):
            entries.append(fn)
        else:
            sys.exit(f"index {idx} would leave a gap after {START + len(entries) - 1}")

        if name not in names:
            names.append(name)
        msg_id = port.msg_id_for_index(names.index(name))
        descs[name] = desc

        buf = bytearray(gi.vfs.read(gi.proto_path(tmpl)))
        struct.pack_into(">i", buf, 0, (1 << 24) | idx)
        struct.pack_into(">i", buf, 4, msg_id)
        struct.pack_into(">i", buf, 8, 0x01000000 | art_index(art))
        struct.pack_into(">i", buf, 28, -1)
        struct.pack_into(">i", buf, 40, TEAM)
        flags = struct.unpack_from(">i", buf, CRITTER_FLAGS_OFF)[0]
        if idx in BARTER:
            flags |= CRITTER_BARTER
        struct.pack_into(">i", buf, CRITTER_FLAGS_OFF, flags)
        set_total(buf, STAT_MAX_HP, hp)
        struct.pack_into(">i", buf, STATS_OFF + 4 * STAT_GENDER, gender)
        if gun:
            skill, value = gun
            for s, i in GUN.items():
                struct.pack_into(">i", buf, SKILLS_OFF + 4 * i, value if s == skill else 0)
        print(f"  {fn}  {name:22} art {art:7} hp {hp:3}  msg {msg_id}")
        if not args.dry_run:
            (CRIT_DIR / fn).write_bytes(bytes(buf))

    if args.dry_run:
        return 0
    REG.write_text("\n".join(reg[:header] + entries) + "\n", encoding="utf-8")
    NAMES.write_text("\n".join(names) + "\n", encoding="utf-8")
    DESCS.write_text("".join(f"{k}\t{v}\n" for k, v in descs.items()), encoding="utf-8")
    port.write_merged_msg("critters")
    print("names and descriptions written; now run gen_ids.py, build.py, deploy.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
